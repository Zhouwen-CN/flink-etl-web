// ============================== 消息 ==============================

/** ChatRequest，对话请求对象 */
export interface SendDTO {
  appId?: string
  /** 上下文的条数 */
  contentNumber?: number
  /** 是否开启mcp */
  isMcp?: boolean
  /** 知识库id */
  kid?: string
  messages: Message[]
  model?: string
  /** 提示词 */
  prompt?: string
  /** 是否开启联网搜索(0关闭 1开启) */
  search?: boolean
  /** 会话id */
  sessionId?: string
  /** 是否开启流式对话 */
  stream?: boolean
  /** 系统提示词 */
  sysPrompt?: string
  /** 用户id */
  userId?: number
  /** 是否携带上下文 */
  usingContext?: boolean
}

/** Message，对话消息 */
export interface Message {
  content?: string
  name?: string
  reasoning_content?: string
  role?: "system" | "user" | "assistant" | "function" | "tool"
  tool_call_id?: string
  tool_calls?: ToolCalls[]
}

/** ToolCalls，The tool calls generated by the model, such as function calls. */
export interface ToolCalls {
  function?: ToolCallFunction
  id?: string
  type?: string
}

export interface ToolCallFunction {
  arguments?: string
  name?: string
}

